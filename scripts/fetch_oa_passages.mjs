/**
 * Refresh stored Introduction/Discussion passages for open-access papers.
 * Keeps the previous text when a publisher blocks the fetch.
 * Usage: node scripts/fetch_oa_passages.mjs [doi ...]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fetchFreshPassages } from '../functions/_lib/fulltext.js';
import { OA_PASSAGES } from '../functions/_lib/oa-passages.js';

const args = process.argv.slice(2).map(s => s.trim().toLowerCase()).filter(Boolean);
const dois = args.length ? args : Object.keys(OA_PASSAGES);
const next = { ...OA_PASSAGES };
let changed = 0;
for (const doi of dois) {
  try {
    const text = await fetchFreshPassages(doi);
    if (text && text.length > 400) {
      next[doi] = text;
      changed++;
      console.log('updated', doi, text.length);
    } else {
      console.log('kept', doi, next[doi] ? 'previous' : 'empty');
    }
  } catch (err) {
    console.log('kept', doi, err?.message || err);
  }
}
const body = '/** Open-access Introduction and Discussion text, keyed by lowercase DOI.\n'
  + ' * Regenerated by scripts/fetch_oa_passages.mjs. Preprint text is not stored here.\n'
  + ' */\nexport const OA_PASSAGES = ' + JSON.stringify(next, null, 2) + ';\n';
writeFileSync(new URL('../functions/_lib/oa-passages.js', import.meta.url), body);
console.log('changed', changed);
